using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.IO;
using System.Linq;
using System.Text;
using FlexVerse.SourceGenerators;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Xunit;

namespace FlexVerse.Test.SourceGenerators
{
    /// <summary>
    /// Runs FlexVerseGenerator in-process via Microsoft.CodeAnalysis.
    ///
    /// The fixture widget compiles against the real FlexVerse.dll (net48) plus
    /// the RimWorld/Unity *reference* assemblies as metadata only; no Unity or
    /// Verse type is ever executed. Oracle substrings in the golden tests are
    /// stable because WidgetEmitter writes every member with a deterministic
    /// CodeBuilder layout.
    /// </summary>
    public class WidgetEmitterTests
    {
        private const string FixtureWidget = """
            using FlexVerse;

            namespace FVGen
            {
                public partial class SampleWidget : Widget
                {
                    [Prop] public Behavior<float> Speed { get; set; }
                    [State] public Behavior<float> Alpha { get; set; }
                }
            }
            """;

        [Fact]
        public void SampleWidgetWithPropAndState_CompilesWithoutErrors_AfterGeneration()
        {
            var (diagnostics, _) = GeneratorRunner.Run(FixtureWidget);

            var errors = diagnostics.Where(d => d.Severity == DiagnosticSeverity.Error).ToList();
            Assert.True(
                errors.Count == 0,
                "Expected zero compilation errors, got:\n"
                    + string.Join("\n", errors.Select(d => $"{d.Id}: {d.GetMessage()}"))
            );
        }

        [Fact]
        public void EmittedSource_ContainsPropRegionWithExpectedGeneratedMembers_Oracle()
        {
            var (_, generated) = GeneratorRunner.Run(FixtureWidget);

            Assert.Contains("#region Prop", generated);
            Assert.Contains("protected Behavior<float> _Speed", generated);
            Assert.Contains("protected Action _speedChanging;", generated);
            Assert.Contains("protected Action _speedChanged;", generated);
            Assert.Contains("protected Behavior<float> _speed", generated);
        }

        [Fact]
        public void EmittedSource_ContainsStateRegionWithExpectedGeneratedMembers_Oracle()
        {
            var (_, generated) = GeneratorRunner.Run(FixtureWidget);

            Assert.Contains("#region State", generated);
            Assert.Contains("protected Behavior<float> _Alpha", generated);
            Assert.Contains("protected Action _alphaChanging;", generated);
            Assert.Contains("protected Action _alphaChanged;", generated);
            Assert.Contains("protected Behavior<float> _alpha", generated);
        }

        [Fact]
        public void EmittedSource_SwitchesOverWidgetLifecycleWithDefinitionAndInstanceCases_Oracle()
        {
            var (_, generated) = GeneratorRunner.Run(FixtureWidget);

            Assert.Contains("switch (this.LifecycleState)", generated);
            Assert.Contains("case Widget.Lifecycle.Definition:", generated);
            Assert.Contains("case Widget.Lifecycle.Instance:", generated);
            Assert.Contains("this.ActivateBehavior(@new);", generated);
            Assert.Contains("this.ReleaseBehavior(@old);", generated);
        }

        [Fact]
        public void EmittedSource_UsesAutoGeneratedBannerAndFlexVerseUsing_WithoutBaseWidgetFlag()
        {
            var (_, generated) = GeneratorRunner.Run(FixtureWidget);

            Assert.StartsWith("/* <auto-generated /> */", generated);
            Assert.Contains("using FlexVerse;", generated);

            Assert.DoesNotContain("protected bool _isInitializing", generated);
        }

        [Fact]
        public void EmittedSource_IsSelfContainedInFixtureNamespace_Oracle()
        {
            var (_, generated) = GeneratorRunner.Run(FixtureWidget);

            Assert.Contains("namespace FVGen", generated);
            Assert.Contains("class SampleWidget", generated);
        }
    }
}
