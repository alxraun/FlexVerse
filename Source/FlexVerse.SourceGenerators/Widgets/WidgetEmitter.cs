using System.Linq;
using FlexVerse.SourceGenerators.Widgets.Emitters;
using FlexVerse.SourceGenerators.Widgets.Models;

namespace FlexVerse.SourceGenerators.Widgets
{
    internal static class WidgetEmitter
    {
        private static readonly string[] MandatoryUsings =
        {
            "System",
            "System.Collections.Generic",
            "System.Linq",
            "UnityEngine",
            "FlexVerse",
        };

        /// <summary>Performs the Emit operation.</summary>
        public static string Emit(WidgetModel model)
        {
            var cb = new CodeBuilder();

            cb.Line("/* <auto-generated /> */");
            cb.Line();

            var userUsings = model
                .Usings.Select(u => u.Trim().TrimEnd(';'))
                .Where(u => u.StartsWith("using "))
                .Select(u => u.Substring(6).Trim());

            var allUsings = MandatoryUsings
                .Concat(userUsings)
                .Distinct()
                .OrderBy(ns => ns.Length)
                .ThenBy(ns => ns)
                .Select(ns => $"using {ns};");

            foreach (var usingDirective in allUsings)
            {
                cb.Line(usingDirective);
            }
            cb.Line();

            if (!string.IsNullOrEmpty(model.Namespace))
            {
                cb.Line($"namespace {model.Namespace}");
                cb.Block(() => EmitTypeDeclarations(cb, model, 0));
            }
            else
            {
                EmitTypeDeclarations(cb, model, 0);
            }

            return cb.ToString();
        }

        private static void EmitTypeDeclarations(CodeBuilder cb, WidgetModel model, int index)
        {
            if (index < model.Hierarchy.Length - 1)
            {
                var containingType = model.Hierarchy[index];
                cb.Line(containingType.Header);
                cb.Block(() => EmitTypeDeclarations(cb, model, index + 1));
            }
            else
            {
                EmitClassDeclaration(cb, model);
            }
        }

        private static void EmitClassDeclaration(CodeBuilder cb, WidgetModel model)
        {
            var widgetStructure = model.WidgetStructure;
            cb.Line(widgetStructure.Header);

            cb.Block(() =>
            {
                if (model.IsBase)
                {
                    cb.Line("protected bool _isInitializing = false;");
                    cb.Line();
                }

                new Emitters.Fvp().Emit(cb, model);
                new Prop().Emit(cb, model);
                new State().Emit(cb, model);
                new InheritedContext().Emit(cb, model);

                new InitMembersFromCreation().Emit(cb, model);
                new InitMembersFromDefinition().Emit(cb, model);
                new ApplyPropsFromDefinition().Emit(cb, model);
                new CloneMembersFromDefinition().Emit(cb, model);
                new InitInheritedContext().Emit(cb, model);
                new DeinitInheritedContext().Emit(cb, model);
                new ReleaseBehaviors().Emit(cb, model);
                new ReleaseBehavior().Emit(cb, model);
                new ActivateBehavior().Emit(cb, model);
                new Clone().Emit(cb, model);

                new Refs().Emit(cb, model);
                new BindRefs().Emit(cb, model);
                new WatchRefs().Emit(cb, model);
            });
        }
    }
}
