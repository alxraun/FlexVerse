using System.Linq;
using FlexVerse.SourceGenerators.Fvp.Emitters;
using FlexVerse.SourceGenerators.Fvp.Models;

namespace FlexVerse.SourceGenerators.Fvp
{
    /// <summary>Emission orchestration — mirrors WidgetEmitter: usings assembly,</summary>
    public static class FvpEmitter
    {
        private static readonly string[] MandatoryUsings = { "System", "FlexVerse" };

        /// <summary>Performs the Emit operation.</summary>
        public static string Emit(FvpModel model)
        {
            var cb = new CodeBuilder();

            cb.Line("/* <auto-generated /> */");
            cb.Line();

            var userUsings = model
                .Usings.Select(u => u.Trim().TrimEnd(';'))
                .Where(u => u.StartsWith("using "))
                .Select(u => u.Substring(6).Trim());

            var allUsings = MandatoryUsings
                .Concat(userUsings)
                .Distinct()
                .OrderBy(ns => ns.Length)
                .ThenBy(ns => ns)
                .Select(ns => $"using {ns};");

            foreach (var usingDirective in allUsings)
            {
                cb.Line(usingDirective);
            }
            cb.Line();

            if (!string.IsNullOrEmpty(model.Namespace))
            {
                cb.Line($"namespace {model.Namespace}");
                cb.Block(() => EmitTypeDeclarations(cb, model, 0));
            }
            else
            {
                EmitTypeDeclarations(cb, model, 0);
            }

            return cb.ToString();
        }

        private static void EmitTypeDeclarations(CodeBuilder cb, FvpModel model, int index)
        {
            if (index < model.Hierarchy.Length - 1)
            {
                var containingType = model.Hierarchy[index];
                cb.Line(containingType.Header);
                cb.Block(() => EmitTypeDeclarations(cb, model, index + 1));
            }
            else
            {
                cb.Line(model.Structure.Header);
                cb.Block(() => EmitMembers(cb, model));
            }
        }

        private static void EmitMembers(CodeBuilder cb, FvpModel model)
        {
            new Emitters.Fvp().Emit(cb, model);
            new EnsureFvpInitialized().Emit(cb, model);
            new ActivateBehavior().Emit(cb, model);
            new ReleaseBehavior().Emit(cb, model);
            new ReleaseBehaviors().Emit(cb, model);
            new ReleaseFvp().Emit(cb, model);
            new Refs().Emit(cb, model);
            new BindRefs().Emit(cb, model);
            new WatchRefs().Emit(cb, model);
        }
    }
}
